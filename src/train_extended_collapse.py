"""
Extended Model Collapse.

Recursive pipeline, structurally identical to train_collapse.py:

    Data^0 (real)              -> train Model_0 -> eval on fixed val/test
    Data^1 (Model_0-generated) -> pool = D0+D1   -> train Model_1 (fresh init)
    Data^2 (Model_1-generated) -> pool = D0+D1+D2 -> train Model_2 (fresh init)
    ...

The difference from the base pipeline is what the model emits. Base predicts
one token -- the query's label -- which is deterministic given the context, so
the only thing recursive training can corrupt is correctness. Extended predicts
three: the query's label, the next symbol, and that symbol's value. The middle
one is genuinely stochastic, so it carries a real distribution over the symbol
vocabulary that recursive self-training can contract. Every hyperparameter is
kept identical to config_collapse.yaml so the two pipelines form a controlled
comparison.

Metric attribution (matters when reading the summary CSV)
---------------------------------------------------------
The data_* columns on row i describe Data^i, which was generated by model i-1
(row 0 therefore describes the TRUE distribution and is the reference against
which every later row is read). The test_* columns on row i describe model i
itself. So test_* on row i and data_* on row i+1 are the same model measured on
two different context samples.
"""

