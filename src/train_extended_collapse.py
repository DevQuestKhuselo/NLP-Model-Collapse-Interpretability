STEP_FIELDS = [
    "generation", "step",
    "train_loss", "train_acc_t1", "train_acc_t2", "train_acc_t3",
    "val_loss", "val_loss_t1", "val_loss_t2", "val_loss_t3",
    "val_acc_t1", "val_acc_t2", "val_acc_t3",
    "val_perplexity", "train_pool_size",
]

SUMMARY_FIELDS = [
    "generation",
    "test_loss", "test_loss_t1", "test_loss_t2", "test_loss_t3",
    "test_acc_t1", "test_acc_t2", "test_acc_t3",
    "test_perplexity",
    "test_consistency", "test_in_context_fraction", "test_type_validity",
    "test_symbol_entropy", "test_symbol_coverage",
    "data_agreement_t1", "data_agreement_t2", "data_agreement_t3",
    "data_symbol_entropy", "data_symbol_entropy_normalized",
    "data_symbol_kl_uniform", "data_symbol_coverage",
    "data_symbol_top1_mass", "data_symbol_effective_support",
    "data_label_entropy_yq", "data_label_entropy_ynext",
    "data_type_validity",
    "data_context_consistency", "data_in_context_fraction",
]


def build_model(cfg, generator, device):
    return ExtendedICLTransformer(
        input_dim=generator.input_dim,
        vocab_size=generator.vocab_size,
        d_model=cfg["d_model"],
        num_heads=cfg["num_heads"],
        depth=cfg["depth"],
    ).to(device)


def forward_batch(model, xb, yb, positions):
    """
    Returns (mean loss tensor, per-token losses [B,3], predicted ids [B,3]).

    The three token losses are kept separate because the mean is dominated by
    token 2's irreducible log(K) term -- token 2 asks which of K context
    symbols comes next, and under the true distribution that is a coin flip.
    Reading the aggregate alone would make a healthy model look broken.
    """
    logits = model(xb, positions=positions)
    B, n_tok, vocab = logits.shape
    tok_losses = F.cross_entropy(
        logits.reshape(B * n_tok, vocab), yb.reshape(B * n_tok), reduction="none"
    ).view(B, n_tok)
    return tok_losses.mean(), tok_losses.detach(), logits.argmax(-1).detach()


@torch.no_grad()
def evaluate_on_set(model, x, y, positions, device, batch_size=256):
    """Full-pass evaluation over a fixed (x, y) tensor set."""
    model.eval()
    n = x.shape[0]
    loss_sum = torch.zeros(3)
    correct = torch.zeros(3)

    for start in range(0, n, batch_size):
        xb = x[start:start + batch_size].to(device)
        yb = y[start:start + batch_size].to(device)
        _, tok_losses, preds = forward_batch(model, xb, yb, positions)
        loss_sum += tok_losses.sum(0).cpu()
        correct += (preds == yb).float().sum(0).cpu()

    model.train()
    tok_loss = (loss_sum / n).tolist()
    tok_acc = (correct / n).tolist()
    mean_loss = float(np.mean(tok_loss))
    return mean_loss, tok_loss, tok_acc, float(np.exp(mean_loss))


def describe_generated_data(cont_ids, true_cont_ids, meta, cfg):
    """Distributional summary of one generation's data (Data^i)."""
    nc, nl = cfg["num_classes"], cfg["num_labels"]
    sym = distribution_stats(symbol_counts(cont_ids, nc))
    yq = distribution_stats(label_counts(cont_ids, 0, nc, nl))
    ynext = distribution_stats(label_counts(cont_ids, 2, nc, nl))
    agreement = per_token_accuracy(cont_ids, true_cont_ids)
    consistency, in_context = context_consistency(cont_ids, meta, nc)

    return {
        "data_agreement_t1": agreement[0],
        "data_agreement_t2": agreement[1],
        "data_agreement_t3": agreement[2],
        "data_symbol_entropy": sym["entropy"],
        "data_symbol_entropy_normalized": sym["entropy_normalized"],
        "data_symbol_kl_uniform": sym["kl_to_uniform"],
        "data_symbol_coverage": sym["coverage"],
        "data_symbol_top1_mass": sym["top1_mass"],
        "data_symbol_effective_support": sym["effective_support"],
        "data_label_entropy_yq": yq["entropy"],
        "data_label_entropy_ynext": ynext["entropy"],
        "data_type_validity": type_validity(cont_ids, nc, nl),
        "data_context_consistency": consistency,
        "data_in_context_fraction": in_context,
    }


def describe_test_rollout(model, test_x, test_meta, generator, cfg, device):
    """
    Let the trained model generate freely on the FIXED test contexts.

    This is the cross-generation-comparable view of generative behaviour: same
    contexts every generation, so any drift is the model's, not the sample's.
    """
    nc, nl = cfg["num_classes"], cfg["num_labels"]
    _, cont_ids = rollout_continuation(
        model, test_x, generator,
        decode=cfg.get("decode", "sample"),
        temperature=cfg.get("temperature", 1.0),
        device=device,
    )
    consistency, in_context = context_consistency(cont_ids, test_meta, nc)
    sym = distribution_stats(symbol_counts(cont_ids, nc))
    return {
        "test_consistency": consistency,
        "test_in_context_fraction": in_context,
        "test_type_validity": type_validity(cont_ids, nc, nl),
        "test_symbol_entropy": sym["entropy"],
        "test_symbol_coverage": sym["coverage"],
    }


def train_one_generation(cfg, model, train_x, train_y, val_x, val_y, positions,
                         device, gen_idx, csv_writer, csv_file):
    """
    Train `model` from scratch on (train_x, train_y) for cfg['train_steps']
    steps, periodically evaluating on the fixed val set.
    """
    optimizer = torch.optim.Adam(model.parameters(), lr=cfg["lr"])

    for step in range(1, cfg["train_steps"] + 1):
        xb, yb = sample_batch(train_x, train_y, cfg["batch_size"], device)

        loss, tok_losses, preds = forward_batch(model, xb, yb, positions)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        if step % cfg["eval_every"] == 0 or step == cfg["train_steps"]:
            train_acc = (preds == yb).float().mean(0).tolist()
            val_loss, val_tok_loss, val_tok_acc, val_ppl = evaluate_on_set(
                model, val_x, val_y, positions, device, batch_size=cfg["batch_size"]
            )

            print(
                f"[gen {gen_idx}] step {step}/{cfg['train_steps']} "
                f"train_loss={loss.item():.4f} "
                f"val_loss={val_loss:.4f} "
                f"val_acc y_q={val_tok_acc[0]:.3f} "
                f"x_next={val_tok_acc[1]:.3f} y_next={val_tok_acc[2]:.3f}"
            )

            csv_writer.writerow({
                "generation": gen_idx,
                "step": step,
                "train_loss": loss.item(),
                "train_acc_t1": train_acc[0],
                "train_acc_t2": train_acc[1],
                "train_acc_t3": train_acc[2],
                "val_loss": val_loss,
                "val_loss_t1": val_tok_loss[0],
                "val_loss_t2": val_tok_loss[1],
                "val_loss_t3": val_tok_loss[2],
                "val_acc_t1": val_tok_acc[0],
                "val_acc_t2": val_tok_acc[1],
                "val_acc_t3": val_tok_acc[2],
                "val_perplexity": val_ppl,
                "train_pool_size": train_x.shape[0],
            })
            csv_file.flush()

    return model


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="config_extended_collapse.yaml")
    args = parser.parse_args()

    with open(args.config, "r") as f:
        cfg = yaml.safe_load(f)

    set_seed(cfg["seed"])
    device = resolve_device(cfg["device"])
    print("device:", device)
    print("decode:", cfg.get("decode", "sample"),
          "temperature:", cfg.get("temperature", 1.0))

    data_dir = cfg["data_dir"]
    checkpoint_dir = cfg["checkpoint_dir"]
    Path(checkpoint_dir).mkdir(parents=True, exist_ok=True)
    Path(data_dir).mkdir(parents=True, exist_ok=True)
    Path(os.path.dirname(cfg["results_csv"])).mkdir(parents=True, exist_ok=True)

    generator = make_true_extended_generator(cfg, device)
    positions = generator.pred_positions

    # --- Fixed val/test sets, sampled once from the true distribution ---
    (val_x, val_y, _), (test_x, test_y, test_meta) = \
        generate_fixed_extended_eval_sets(cfg, device)
    torch.save({"x": val_x.cpu(), "y": val_y}, os.path.join(data_dir, "fixed_val.pt"))
    torch.save({"x": test_x.cpu(), "y": test_y}, os.path.join(data_dir, "fixed_test.pt"))

    step_file = open(cfg["results_csv"], "w", newline="")
    step_writer = csv.DictWriter(step_file, fieldnames=STEP_FIELDS)
    step_writer.writeheader()

    summary_rows = []
    symbol_hist_rows = []
    model = None

    for gen_idx in range(cfg["num_generations"]):
        print(f"\n=== Generation {gen_idx} ===")

        # --- Build this generation's Data^i and save it ---
        if gen_idx == 0:
            gen_x, gen_ids, meta = generate_extended_generation_zero_train(cfg, device)
            true_ids = gen_ids  # gen 0 continuations ARE the true ones
        else:
            gen_x, gen_ids, true_ids, meta = \
                generate_next_extended_generation_train(cfg, device, model)

        data_row = describe_generated_data(gen_ids, true_ids, meta, cfg)
        print(f"Data^{gen_idx}: symbol entropy="
              f"{data_row['data_symbol_entropy']:.3f} nats, "
              f"coverage={int(data_row['data_symbol_coverage'])}"
              f"/{cfg['num_classes']}, "
              f"consistency={data_row['data_context_consistency']:.3f}, "
              f"y_q agreement={data_row['data_agreement_t1']:.3f}")

        counts = symbol_counts(gen_ids, cfg["num_classes"])
        for cls, count in enumerate(counts.tolist()):
            symbol_hist_rows.append({
                "generation": gen_idx, "class_id": cls, "count": int(count),
            })

        save_generation(data_dir, gen_idx, gen_x, gen_ids, split="train")

        # --- Accumulated training pool: D0 u D1 u ... u D{gen_idx} ---
        train_x, train_y = build_accumulated_train_set(data_dir, gen_idx)
        print(f"Accumulated training pool size: {train_x.shape[0]}")

        # --- Fresh model each generation, trained from scratch ---
        model = build_model(cfg, generator, device)
        model = train_one_generation(
            cfg, model, train_x, train_y, val_x, val_y, positions,
            device, gen_idx, step_writer, step_file,
        )

        ckpt_path = os.path.join(checkpoint_dir, f"extended_collapse_gen_{gen_idx}.pt")
        torch.save({
            "model_state": model.state_dict(),
            "config": cfg,
            "input_dim": generator.input_dim,
            "vocab_size": generator.vocab_size,
        }, ckpt_path)
        print(f"Saved checkpoint: {ckpt_path}")

        # --- Test on the FIXED test set ---
        test_loss, test_tok_loss, test_tok_acc, test_ppl = evaluate_on_set(
            model, test_x, test_y, positions, device, batch_size=cfg["batch_size"]
        )
        rollout_row = describe_test_rollout(
            model, test_x, test_meta, generator, cfg, device
        )
        print(f"[gen {gen_idx}] TEST loss={test_loss:.4f} "
              f"acc y_q={test_tok_acc[0]:.3f} x_next={test_tok_acc[1]:.3f} "
              f"y_next={test_tok_acc[2]:.3f} "
              f"self-consistency={rollout_row['test_consistency']:.3f}")

        row = {
            "generation": gen_idx,
            "test_loss": test_loss,
            "test_loss_t1": test_tok_loss[0],
            "test_loss_t2": test_tok_loss[1],
            "test_loss_t3": test_tok_loss[2],
            "test_acc_t1": test_tok_acc[0],
            "test_acc_t2": test_tok_acc[1],
            "test_acc_t3": test_tok_acc[2],
            "test_perplexity": test_ppl,
        }
        row.update(rollout_row)
        row.update(data_row)
        summary_rows.append(row)

    step_file.close()

    summary_path = cfg["results_csv"].replace(".csv", "_test_summary.csv")
    with open(summary_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=SUMMARY_FIELDS)
        writer.writeheader()
        writer.writerows(summary_rows)

    hist_path = cfg["results_csv"].replace(".csv", "_symbol_counts.csv")
    with open(hist_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["generation", "class_id", "count"])
        writer.writeheader()
        writer.writerows(symbol_hist_rows)

    print(f"\nDone. Step-level metrics: {cfg['results_csv']}")
    print(f"Per-generation summary: {summary_path}")
    print(f"Symbol histograms: {hist_path}")


if __name__ == "__main__":
    main()
