"""
Extended Model Collapse.

Recursive pipeline, structurally identical to train_collapse.py:

    Data^0 (real)              -> train Model_0 -> eval on fixed val/test
    Data^1 (Model_0-generated) -> pool = D0+D1   -> train Model_1 (fresh init)
    Data^2 (Model_1-generated) -> pool = D0+D1+D2 -> train Model_2 (fresh init)
    ...

The difference from the base pipeline is what the model emits. Base predicts
one token -- the query's label -- which is deterministic given the context, so
the only thing recursive training can corrupt is correctness. Extended predicts
three: the query's label, the next symbol, and that symbol's value. The middle
one is a coin flip between the context symbols, so it carries a real
distribution that recursive self-training can distort. The task, architecture
and optimiser settings are kept identical to config_collapse.yaml so the two
pipelines form a controlled comparison.

Three things go beyond the base pipeline. The README's "Methodological
revisions" section gives the evidence behind each:

- Checkpoint selection. A slice of each generation's pool is held out, and the
  checkpoint with the lowest loss on it is kept. Training to the last step let
  Model_0 memorise which symbol came next in each training sequence, so the
  loop started from a model that had already collapsed. Selection never looks
  at the fixed val/test sets, so real data cannot steer the synthetic loop.
- A matched real-data control (--control). The pool grows every generation,
  so "later generation" also means "more data". The control grows the pool
  with real data instead, to the same sizes, so the gap between the two runs
  is the effect of training on model output.
- Seeds. --seeds runs independent replicates, each into its own directories.

Metric attribution (matters when reading the summary CSV)
---------------------------------------------------------
The data_* columns on row i describe Data^i, which was generated by model i-1
(row 0 therefore describes the TRUE distribution and is the reference against
which every later row is read). The test_* columns on row i describe model i
itself, measured on the fixed test contexts -- so only test_* columns are
comparable down a column as "what generation i's model does". test_next_* are
model i's own x_next probabilities, which is where collapse of the next-symbol
choice is visible (see extended_metrics.py for why data_* cannot show it).
"""

